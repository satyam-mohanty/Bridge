package com.bridge.android.update.model

import com.bridge.android.update.crypto.Ed25519Verifier
import com.bridge.android.update.data.UpdateConfig
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class UpdateManifestTest {

    private val verifier = Ed25519Verifier.fromHex(UpdateConfig.UPDATE_PUBLIC_KEY_HEX)

    @Test
    fun testManifestParsing() {
        val json = """
            {
              "versionCode": 2,
              "versionName": "1.1.0",
              "minSupportedVersionCode": 1,
              "apkUrl": "https://github.com/satyam-mohanty/Bridge/releases/download/v1.1.0/bridge.apk",
              "apkSha256": "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
              "apkSizeBytes": 15000000,
              "releaseNotes": "Performance improvements and bug fixes.",
              "publishedAt": "2026-10-21T12:00:00Z",
              "mandatory": false,
              "signature": "test_signature"
            }
        """.trimIndent()

        val manifest = UpdateManifest.fromJson(json)
        assertEquals(2L, manifest.versionCode)
        assertEquals("1.1.0", manifest.versionName)
        assertEquals(1L, manifest.minSupportedVersionCode)
        assertEquals("https://github.com/satyam-mohanty/Bridge/releases/download/v1.1.0/bridge.apk", manifest.apkUrl)
        assertEquals("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", manifest.apkSha256)
        assertEquals(15000000L, manifest.apkSizeBytes)
        assertEquals("Performance improvements and bug fixes.", manifest.releaseNotes)
        assertEquals(false, manifest.mandatory)
        assertEquals("test_signature", manifest.signature)
    }

    @Test
    fun testCanonicalPayloadDeterministic() {
        val manifest = UpdateManifest(
            versionCode = 2,
            versionName = "1.1.0",
            apkUrl = "https://example.com/app.apk",
            apkSha256 = "ABCD1234EF5678",
            apkSizeBytes = 12345,
            releaseNotes = "Notes line 1\nNotes line 2"
        )

        val payload = String(manifest.getCanonicalPayload(), Charsets.UTF_8)
        val expected = "v1\n2\n1.1.0\nhttps://example.com/app.apk\nabcd1234ef5678\n12345\nNotes line 1\nNotes line 2"
        assertEquals(expected, payload)
    }

    @Test
    fun testSignedManifestVerification() {
        // Test with Python generator's signature
        // We'll generate a test keypair and verify with Ed25519Verifier
        val pubKeyHex = "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a"
        val testVerifier = Ed25519Verifier.fromHex(pubKeyHex)

        // RFC 8032 test vector 1 signature over empty message
        val emptyManifest = UpdateManifest(
            versionCode = 0,
            versionName = "",
            apkUrl = "",
            apkSha256 = "",
            apkSizeBytes = 0,
            releaseNotes = "",
            signature = "e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b"
        )
        // With tampered signature, verifySignature must return false
        assertFalse(emptyManifest.verifySignature(testVerifier))
    }

    @Test
    fun testGeneratedReleaseManifestVerifies() {
        // Read manifest generated by publish_manifest.py if available
        val manifestFile = java.io.File("../release/update-manifest.json")
        if (manifestFile.exists()) {
            val json = manifestFile.readText(Charsets.UTF_8)
            val manifest = UpdateManifest.fromJson(json)
            assertTrue("Generated release manifest signature must verify with embedded public key", manifest.verifySignature(verifier))
        }
    }
}
